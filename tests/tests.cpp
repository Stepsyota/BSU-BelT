TEST_P(BelTParameterizedTest, EncryptText) {
    const auto& params = GetParam();
    BelT belt(params.key);
    
    std::vector<uint8_t> encrypted;
    
    if (params.mode == CipherMode::ECB) {
        encrypted = belt.encrypt_ecb(params.plain);
    } else if (params.mode == CipherMode::CTR){
        ASSERT_TRUE(params.iv.has_value());
        auto iv_span = std::span<const uint8_t, 16>(params.iv->data(), 16);
        encrypted = belt.encrypt_ctr(params.plain, iv_span);
    } else if (params.mode == CipherMode::CBC){
        ASSERT_TRUE(params.iv.has_value());
        auto iv_span = std::span<const uint8_t, 16>(params.iv->data(), 16);
        encrypted = belt.encrypt_cbc(params.plain, iv_span);
    }
    
    ASSERT_TRUE(std::ranges::equal(encrypted, params.cipher));
}

